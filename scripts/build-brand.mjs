/**
 * Emits every static brand asset from lib/brand/mark.json.
 *
 * The app renders the mark through components/brand/LogoMark.tsx, which reads
 * the same JSON. Generating the install icons from it rather than maintaining
 * a second copy is the only way the home-screen icon and the on-screen logo
 * stay the same drawing — an earlier hand-kept duplicate had already drifted.
 *
 * PNGs exist because Chrome will take an SVG from the manifest but Android's
 * launcher and iOS's home screen want bitmaps, and iOS will not read SVG at
 * all. SVG-only is how an install ends up with a blank icon.
 *
 * Run: node scripts/build-brand.mjs
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const m = JSON.parse(await readFile(path.join(ROOT, 'lib/brand/mark.json'), 'utf8'));

const n = (v) => String(Number(v.toFixed(4)));

function gradient(id, g) {
  const stops = g.stops
    .map(([o, c, a]) => `<stop offset="${o}" stop-color="${c}"${a < 1 ? ` stop-opacity="${a}"` : ''}/>`)
    .join('');
  return g.type === 'linear'
    ? `<linearGradient id="${id}" x1="${g.x1}" y1="${g.y1}" x2="${g.x2}" y2="${g.y2}" gradientUnits="userSpaceOnUse">${stops}</linearGradient>`
    : `<radialGradient id="${id}" cx="${g.cx}" cy="${g.cy}" r="${g.r}">${stops}</radialGradient>`;
}

const defs = [
  ...Object.entries(m.gradients).map(([k, g]) => gradient(k, g)),
  `<clipPath id="globeClip"><circle cx="${m.globe.cx}" cy="${m.globe.cy}" r="${m.globe.r}"/></clipPath>`,
].join('');

/** The mark itself, without any ground behind it. */
const art = [
  `<path d="${m.shield.d}" fill="none" stroke="url(#sweep)" stroke-width="${m.shield.width}" stroke-linejoin="round" stroke-linecap="round"/>`,
  `<path d="${m.eye.d}" fill="${m.eye.fill}" stroke="url(#rim)" stroke-width="${m.eye.width}" stroke-linejoin="round"/>`,
  `<circle cx="${m.globe.cx}" cy="${m.globe.cy}" r="${m.globe.r}" fill="url(#globe)"/>`,
  `<g clip-path="url(#globeClip)">${m.land.map((l) => `<path d="${l.d}" fill="url(#land)"${l.opacity < 1 ? ` opacity="${l.opacity}"` : ''}/>`).join('')}</g>`,
  `<circle cx="${m.specular.cx}" cy="${m.specular.cy}" r="${m.specular.r}" fill="#FFFFFF" opacity="${m.specular.opacity}"/>`,
  `<circle cx="${m.globe.cx}" cy="${m.globe.cy}" r="${m.globe.r}" fill="url(#gloss)"/>`,
  `<circle cx="${m.globe.cx}" cy="${m.globe.cy}" r="${m.globe.r}" fill="none" stroke="${m.globeEdge.stroke}" stroke-width="${m.globeEdge.width}" opacity="${m.globeEdge.opacity}"/>`,
  `<path d="${m.handle.d}" stroke="url(#sweep)" stroke-width="${m.handle.width}" stroke-linecap="round"/>`,
  `<g fill="url(#sweep)">${m.motes.map((d) => `<rect x="${d.x}" y="${d.y}" width="${d.size}" height="${d.size}" rx="${d.radius}"${d.opacity < 1 ? ` opacity="${d.opacity}"` : ''}/>`).join('')}</g>`,
].join('');

/** The drawn extent, used to centre the art optically rather than by eye. */
const BOUNDS = { x0: 6.5 - m.shield.width / 2, x1: Math.max(...m.motes.map((d) => d.x + d.size)), y0: 6 - m.shield.width / 2, y1: 52.1 + m.shield.width / 2 };
const cx = (BOUNDS.x0 + BOUNDS.x1) / 2;
const cy = (BOUNDS.y0 + BOUNDS.y1) / 2;

/**
 * @param {{plate?: 'round'|'square'|false, scale?: number, note: string}} opts
 */
function document_({ plate = false, scale = 1, note }) {
  const ground =
    plate === 'round'
      ? `<rect width="64" height="64" rx="${m.plate.radius}" fill="${m.plate.fill}"/>`
      : plate === 'square'
        ? `<rect width="64" height="64" fill="${m.plate.fill}"/>`
        : '';
  // Centre on the box, then scale about that centre.
  const t = `translate(32 32) scale(${n(scale)}) translate(${n(-cx)} ${n(-cy)})`;
  return `<!--\n  GENERATED by scripts/build-brand.mjs from lib/brand/mark.json — do not edit.\n  ${note}\n-->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${m.viewBox}" role="img" aria-label="TrustLens AI"><title>TrustLens AI</title><defs>${defs}</defs>${ground}<g transform="${t}">${art}</g></svg>\n`;
}

const FILES = [
  ['app/icon.svg', { plate: 'round', scale: 0.92, note: 'The home-screen install icon. The dark plate is load-bearing: an installed icon sits on the user\'s own wallpaper, so it has to carry its own ground or the cyan stroke lands on a photograph.' }],
  ['public/brand/mark.svg', { plate: false, scale: 1, note: 'The mark on its own, for anywhere that already has a background.' }],
  ['public/brand/icon-maskable.svg', { plate: 'square', scale: 0.74, note: 'Maskable. Android crops a home-screen icon to the launcher\'s own shape, so the art sits inside the middle 80% safe zone and the ground bleeds to every edge. The plain icon here would have the magnifier handle and the motes sliced off.' }],
];

await mkdir(path.join(ROOT, 'public/brand'), { recursive: true });
for (const [rel, opts] of FILES) {
  await writeFile(path.join(ROOT, rel), document_(opts));
  console.log(`svg  ${rel}`);
}

const PNGS = [
  ['app/icon.svg', 'icon-192.png', 192],
  ['app/icon.svg', 'icon-512.png', 512],
  ['public/brand/icon-maskable.svg', 'icon-maskable-192.png', 192],
  ['public/brand/icon-maskable.svg', 'icon-maskable-512.png', 512],
  // iOS rounds the corners itself and applies no mask, so it gets the plated art.
  ['app/icon.svg', 'apple-touch-icon.png', 180],
  // Open Graph / link previews want a wide bitmap; handled separately below.
];

for (const [src, name, size] of PNGS) {
  const svg = await readFile(path.join(ROOT, src));
  const png = await sharp(svg, { density: 512 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
  await writeFile(path.join(ROOT, 'public/brand', name), png);
  console.log(`png  public/brand/${name.padEnd(26)} ${size}x${size}  ${(png.length / 1024).toFixed(1)} KB`);
}

console.log('\nBrand assets regenerated.');
